package io.github.xiaou61.ai.internal.rag;

import java.time.Instant;

/** `ai_knowledge_chunk_edits` 的一行：某条目某切片的一个手工编辑版本（WORK-076）。 */
class KnowledgeChunkEdit {

    private Long id;
    private Long entryId;
    private Integer chunkIndex;
    private Integer version;
    private String content;
    private String contentHash;
    private byte[] embedding;
    private Integer dimension;
    private String baseContentHash;
    private Long editorId;
    private Instant createdAt;

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public Long getEntryId() {
        return entryId;
    }

    public void setEntryId(Long entryId) {
        this.entryId = entryId;
    }

    public Integer getChunkIndex() {
        return chunkIndex;
    }

    public void setChunkIndex(Integer chunkIndex) {
        this.chunkIndex = chunkIndex;
    }

    public Integer getVersion() {
        return version;
    }

    public void setVersion(Integer version) {
        this.version = version;
    }

    public String getContent() {
        return content;
    }

    public void setContent(String content) {
        this.content = content;
    }

    public String getContentHash() {
        return contentHash;
    }

    public void setContentHash(String contentHash) {
        this.contentHash = contentHash;
    }

    public byte[] getEmbedding() {
        return embedding;
    }

    public void setEmbedding(byte[] embedding) {
        this.embedding = embedding;
    }

    public Integer getDimension() {
        return dimension;
    }

    public void setDimension(Integer dimension) {
        this.dimension = dimension;
    }

    public String getBaseContentHash() {
        return baseContentHash;
    }

    public void setBaseContentHash(String baseContentHash) {
        this.baseContentHash = baseContentHash;
    }

    public Long getEditorId() {
        return editorId;
    }

    public void setEditorId(Long editorId) {
        this.editorId = editorId;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Instant createdAt) {
        this.createdAt = createdAt;
    }
}
